var lastIndex = -1;

function changeRecipe() {
  var randomIndex = Math.floor(Math.random() * recipes.length);

  while (randomIndex == lastIndex) {
    randomIndex = Math.floor(Math.random() * recipes.length);
  }
  lastIndex = randomIndex;

  var recipe = recipes[randomIndex];

  document.getElementById("recipe-image").src = recipe.image;
  document.getElementById("rating-average").innerHTML = recipe.rating;
  document.getElementById("rating-quantity").innerHTML = recipe.reviews;

  document.getElementById("prep-time-display").innerHTML =
    recipe.prepTime + " min";
  document.getElementById("cook-time-display").innerHTML =
    recipe.cookTime + " min";
  document.getElementById("servings-display").innerHTML = recipe.servings;

  document.getElementById("recipe-name").innerHTML = recipe.name;
  document.getElementById("recipe-description").innerHTML = recipe.description;
  document.getElementById("category-badge").innerHTML = recipe.category;

  var difficultyBadge = document.getElementById("difficulty-badge");
  difficultyBadge.innerHTML = recipe.difficulty;
  difficultyBadge.className =
    "badge rounded-pill px-3 py-2 badge-difficulty fw-semibold";

  if (recipe.difficulty == "Intermediate") {
    difficultyBadge.classList.add("badge-intermediate");
  } else if (recipe.difficulty == "Hard") {
    difficultyBadge.classList.add("badge-hard");
  }

  var totalTime = recipe.prepTime + recipe.cookTime;
  var warningAlert = document.getElementById("time-warning");

  if (totalTime > 45) {
    warningAlert.classList.remove("d-none");
  } else {
    warningAlert.classList.add("d-none");
  }

  var ingredientsHTML = "";
  for (var i = 0; i < recipe.ingredients.length; i++) {
    ingredientsHTML +=
      '<li class="d-flex align-items-start gap-3">' +
      '<span class="step-circle rounded-circle fw-bold small flex-shrink-0">' +
      (i + 1) +
      "</span>" +
      '<span class="text-secondary-emphasis">' +
      recipe.ingredients[i] +
      "</span>" +
      "</li>";
  }
  document.getElementById("ingredients-list").innerHTML = ingredientsHTML;

  var instructionsHTML = "";
  for (var i = 0; i < recipe.instructions.length; i++) {
    instructionsHTML +=
      '<div class="d-flex align-items-start gap-3">' +
      '<span class="step-square rounded-4 fw-bold fs-5 flex-shrink-0">' +
      (i + 1) +
      "</span>" +
      '<p class="text-secondary-emphasis pt-2 mb-0">' +
      recipe.instructions[i] +
      "</p>" +
      "</div>";
  }
  document.getElementById("instructions-list").innerHTML = instructionsHTML;

  document.getElementById("calories-value").innerHTML = recipe.calories;
  document.getElementById("protein-value").innerHTML = recipe.protein;
  document.getElementById("carbs-value").innerHTML = recipe.carbs;
  document.getElementById("fat-value").innerHTML = recipe.fat;
  document.getElementById("fiber-value").innerHTML = recipe.fiber;
  document.getElementById("sodium-value").innerHTML = recipe.sodium;

  var tipsHTML = "";
  for (var i = 0; i < recipe.tips.length; i++) {
    tipsHTML +=
      '<div class="tip-card rounded-3 p-3 d-flex align-items-start gap-3">' +
      '<i class="fa-solid fa-circle-check text-amber fs-5 mt-1"></i>' +
      '<p class="text-secondary-emphasis mb-0">' +
      recipe.tips[i] +
      "</p>" +
      "</div>";
  }
  document.getElementById("tips-list").innerHTML = tipsHTML;
}
changeRecipe();
